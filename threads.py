import random
from typing import Optional


@dataclass
class Thread:
    type_emoji: str
    type_name: str
    name: str
    meaning: str
    posts: list[tuple[str, Optional[str]]] = field(default_factory=list)
    # tuple: (female_text, male_text)  |  male_text=None → use female for both


